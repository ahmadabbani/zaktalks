import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const source = readFileSync(new URL('../src/lib/points-rules.js', import.meta.url), 'utf8')
const { purchaseRewardPoints, isValidPointsSelection, pointsDiscountForBalance, pointsSelectionOptions } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`)
assert.equal(purchaseRewardPoints(120000), 1200)
assert.equal(purchaseRewardPoints(120075), 1200)
assert.equal(purchaseRewardPoints(99), 0)
assert.equal(purchaseRewardPoints(0), 0)
assert.throws(() => purchaseRewardPoints(-1))
assert.throws(() => purchaseRewardPoints(undefined))
for (const invalid of [1000, 4000, 5001, -5000, 5000.5, NaN]) assert.equal(isValidPointsSelection(invalid), false)
for (const valid of [0, 5000, 6000, 7000, 10000]) assert.equal(isValidPointsSelection(valid), true)
assert.deepEqual(pointsSelectionOptions(4000), [])
assert.deepEqual(pointsSelectionOptions(5000), [5000])
assert.deepEqual(pointsSelectionOptions(6000), [5000, 6000])
assert.deepEqual(pointsSelectionOptions(7435), [5000, 6000, 7000])
assert.deepEqual(pointsSelectionOptions(10000), [5000, 6000, 7000, 8000, 9000, 10000])
assert.equal(pointsDiscountForBalance(4000, 120000, 5000, 10).eligible, false)
assert.deepEqual(pointsDiscountForBalance(7000, 120000, 5000, 10), { eligible: true, discountPercent: 10, discountCents: 50000, pointsToUse: 5000 })
assert.equal(pointsDiscountForBalance(7000, 120000, 10000, 10).pointsToUse, 7000)
assert.deepEqual(pointsDiscountForBalance(7000, 120000, 6000, 10), { eligible: true, discountPercent: 10, discountCents: 60000, pointsToUse: 6000 })
assert.deepEqual(pointsDiscountForBalance(7000, 120000, 7000, 10), { eligible: true, discountPercent: 10, discountCents: 70000, pointsToUse: 7000 })
assert.deepEqual(pointsDiscountForBalance(12000, 120000, 10000, 10), { eligible: true, discountPercent: 10, discountCents: 100000, pointsToUse: 10000 })
assert.equal(pointsDiscountForBalance(5000, 120000, 5000, 0).eligible, false)
assert.equal(pointsDiscountForBalance(5000, 120000, 1000, 10).eligible, false)
assert.equal(pointsDiscountForBalance(100000, 120000, 100000, 15).discountCents, 120000)
assert.equal(pointsDiscountForBalance(5000, 103, 5000, 10).discountCents, 103)
assert.equal(pointsDiscountForBalance(6000, 120000, 6000, 4).discountCents, 24000)
assert.equal(pointsDiscountForBalance(6000, 200000, 6000, 10).discountCents, 60000, 'Discount is independent of course price')
console.log('PASS: rewards, rounding, minimum, redemption steps, balance cap, multiplier, zero setting and discount cap')
